def select_all_menu(cur):
    cur.execute('''
        SELECT d.title, d.price, c.name
        FROM dish d
        JOIN category c ON c.id = d.category_id
        ORDER BY c.id, d.id;
    ''')
    rows = cur.fetchall()
    for title, price, category in rows:
        print(f'{title} — {float(price):.2f} — {category}')

def select_prices(cur, min_price: float, max_price: float):
    cur.execute('''
        SELECT d.title, d.price, c.name
        FROM dish d
        JOIN category c ON c.id = d.category_id
        WHERE d.price BETWEEN %s AND %s
        ORDER BY d.price, d.id;
    ''', (min_price, max_price))
    rows = cur.fetchall()
    for r in rows:
        print(r)

def select_prefix(cur, pref: str):
    cur.execute('''
        SELECT d.title, d.price, c.name
        FROM dish d
        JOIN category c ON c.id = d.category_id
        WHERE d.title ILIKE %s
        ORDER BY d.title;
    ''', (pref + "%",))
    rows = cur.fetchall()
    for r in rows:
        print(r)

def select_cheap_dishes(cur, numb: int):
    cur.execute('''
        SELECT d.title, d.price, c.name
        FROM dish d
        JOIN category c ON c.id = d.category_id
        ORDER BY d.price ASC, d.id
        LIMIT %s;
    ''', (numb,))
    rows = cur.fetchall()
    for r in rows:
        print(r)

def select_cat_food(cur):
    cur.execute('''
        SELECT c.name, COUNT(d.id)
        FROM category c
        LEFT JOIN dish d ON c.id = d.category_id
        GROUP BY c.id, c.name
        ORDER BY c.id;
    ''')
    rows = cur.fetchall()
    for r in rows:
        print(r)

