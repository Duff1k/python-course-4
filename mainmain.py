import psycopg2

def create_category_table(cur, insert: bool = False):
    cur.execute('''
    CREATE TABLE IF NOT EXISTS category (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL UNIQUE
    );
    ''')
    if insert:
        insert_category_table(cur)

def create_dish_table(cur, insert: bool = False):
    cur.execute('''
    CREATE TABLE IF NOT EXISTS dish (
        id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        title TEXT NOT NULL,
        price NUMERIC(8,2) NOT NULL CHECK (price > 0),
        category_id INT NOT NULL REFERENCES category(id) ON DELETE RESTRICT
    );
    ''')
    if insert:
        insert_dish_table(cur)

